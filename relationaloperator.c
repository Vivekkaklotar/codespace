#include <stdio.h>
int main()
{
    /*
    relational operators :
    < less than
    > grater than
    <= less than or equal to
    >= grater than or equal to
    == equal to
    != not equal to                       */

    int a=10, b=20;
    printf("\n %d\n",a>b);
    printf("\n %d\n",a<b);
    printf("\n %d\n",a<=b);
    printf("\n %d\n",a==b);
    printf("\n %d\n",a!=b);
    return 0;
}